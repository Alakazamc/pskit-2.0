"""Regenerate new-stack contracts in a disposable tree and reject drift."""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT_FILES = (
    "contracts/openapi.json", "contracts/run-event.schema.json", "contracts/compute.schema.json",
    "new_frontend/src/api/generated-events.ts", "new_frontend/src/api/generated-compute.ts",
)


def isolated_env() -> dict[str, str]:
    """Remove inherited application credentials and real database configuration."""
    prefixes = ("RESEARCH_AGENT_", "SUPABASE_", "MODEL_GATEWAY_", "NEW_API_", "PI_")
    env = {key: value for key, value in os.environ.items()
           if not key.startswith(prefixes) and key != "TEST_POSTGRES_DSN"}
    env.update(PYTHONPATH=str(ROOT / "new_backend"), RESEARCH_AGENT_MODE="mock",
               RESEARCH_AGENT_RUNTIME="mock", RESEARCH_AGENT_AF3_EXECUTOR="mock",
               RESEARCH_AGENT_MCP_EXECUTOR="mock")
    return env


def check(python: str, *, typescript: bool = True) -> list[str]:
    """Compare generated bytes without modifying any checked-in contract."""
    with tempfile.TemporaryDirectory(prefix="pskit-contract-check-") as directory:
        target = Path(directory)
        export = target / "new_backend/scripts/export_openapi.py"
        export.parent.mkdir(parents=True)
        shutil.copyfile(ROOT / "new_backend/scripts/export_openapi.py", export)
        (target / "contracts").mkdir()
        generated = target / "new_frontend/src/api"
        generated.mkdir(parents=True)
        subprocess.run([python, str(export)], cwd=target, env=isolated_env(), check=True,
                       timeout=120)
        paths = list(CONTRACT_FILES)
        if typescript:
            compiler = ROOT / "new_frontend/node_modules/.bin/openapi-ts"
            subprocess.run([str(compiler), "--input", str(target / "contracts/openapi.json"),
                            "--output", str(generated / "generated"),
                            "--plugins", "@hey-api/typescript", "--no-log-file"],
                           cwd=target, env=isolated_env(), check=True, timeout=120)
            paths.extend(str(path.relative_to(target))
                         for path in (generated / "generated").rglob("*") if path.is_file())
            paths.extend(str(path.relative_to(ROOT))
                         for path in (ROOT / "new_frontend/src/api/generated").rglob("*")
                         if path.is_file())
        return sorted({name for name in paths
                       if not (ROOT / name).is_file() or not (target / name).is_file()
                       or (ROOT / name).read_bytes() != (target / name).read_bytes()})


def main() -> None:
    """Report filename-only differences; never print API response or credentials."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python", default=sys.executable)
    parser.add_argument("--without-typescript", action="store_true")
    options = parser.parse_args()
    changed = check(options.python, typescript=not options.without_typescript)
    if changed:
        print("Contract drift:\n" + "\n".join(changed), file=sys.stderr)
        raise SystemExit(1)
    print("New-stack contracts match generated Python and TypeScript models")


if __name__ == "__main__":
    main()
